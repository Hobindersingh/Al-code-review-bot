import { sanitizeText } from '../utils/sanitize.js';

const EMOJI = { critical: '🛑', high: '🔴', medium: '🟠', low: '🟡', info: '🔵' };

export const reviewMarker = (sha) => `<!-- aicr:${sha} -->`;

export function formatComment(f) {
  const lines = [
    `${EMOJI[f.severity]} **${f.severity}** · ${f.category} — **${f.title}**`,
    '',
    f.body,
  ];
  if (f.suggestion) lines.push('', '```suggestion', f.suggestion, '```');
  lines.push('', `<sub>confidence ${Math.round(f.confidence * 100)}%</sub>`);
  return lines.join('\n');
}

export function formatReviewBody({ summary, inline, general, headSha, truncatedFiles = 0 }) {
  const all = [...inline, ...general];
  const counts = ['critical', 'high', 'medium', 'low', 'info']
    .map((s) => [s, all.filter((f) => f.severity === s).length])
    .filter(([, n]) => n > 0)
    .map(([s, n]) => `${n} ${s}`)
    .join(', ');

  const out = [`## 🤖 AI Code Review`, '', sanitizeText(summary, 1500), ''];
  out.push(all.length ? `**Findings:** ${counts}` : '**No significant issues found.**');

  if (general.length) {
    out.push('', '**Also noted** (not on a changed line):');
    for (const f of general.slice(0, 10)) {
      out.push(`- ${EMOJI[f.severity]} \`${f.path}:${f.line}\` — **${f.title}**: ${f.body.split('\n')[0].slice(0, 200)}`);
    }
  }
  if (truncatedFiles > 0) out.push('', `_${truncatedFiles} additional file(s) were not reviewed (size limit)._`);
  out.push('', '<sub>Generated by AI and may be wrong. Verify before acting.</sub>', reviewMarker(headSha));
  return out.join('\n');
}
